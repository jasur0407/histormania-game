// Histormania build: validate paths -> bundle into game/js/paths.generated.js
// (with a manifest of the image/audio files that actually exist) -> zip for itch.io.
// Usage: node tools/build.mjs [--no-zip]
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { INCLUDE } from "./build.config.mjs";

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const GAME = join(ROOT, "game");
const DIST = join(ROOT, "dist");
const { validate } = require(join(GAME, "js/validate.js"));

const IMAGE_EXT = [".webp", ".jpg", ".jpeg", ".png"];
const AUDIO_EXT = [".mp3", ".ogg", ".m4a", ".wav"];

// ---- 1. validate ---------------------------------------------------------
const paths = [];
let errorCount = 0;
for (const id of INCLUDE) {
  const file = join(ROOT, "plot/paths", id + ".json");
  const path = JSON.parse(readFileSync(file, "utf8"));
  const report = validate(path);
  console.log(`${id}: ${report.errors.length} errors, ${report.warnings.length} warnings  ${JSON.stringify(report.stats)}`);
  for (const e of [...report.errors, ...report.warnings]) {
    const loc = e.where?.nodeId ? ` (${e.where.nodeId}${e.where.choiceId ? "." + e.where.choiceId : ""})` : "";
    console.log(`  ${e.severity === "error" ? "✗" : "!"} [${e.code}]${loc} ${e.message}`);
  }
  errorCount += report.errors.length;
  if (path.id !== id) { console.log(`  ✗ file name ${id}.json does not match path id '${path.id}'`); errorCount++; }
  delete path.$schema;
  delete path.character?.trueIdentity; // author-only, must never ship to players
  paths.push(path);
}
if (errorCount) { console.error(`\nBuild failed: ${errorCount} error(s).`); process.exit(1); }

// ---- 2. asset manifest -----------------------------------------------------
// Maps a key like "tomb_builder/nile" or "ui/logo" to the file that exists,
// so the game never requests missing files and any image extension works.
function scan(dir, exts) {
  const out = {};
  if (!existsSync(dir)) return out;
  (function walk(d) {
    for (const name of readdirSync(d)) {
      const full = join(d, name);
      if (statSync(full).isDirectory()) { walk(full); continue; }
      const ext = extname(name).toLowerCase();
      if (!exts.includes(ext)) continue;
      const rel = relative(dir, full).split("\\").join("/");
      const key = rel.slice(0, -ext.length).toLowerCase();
      const prev = out[key];
      if (!prev || exts.indexOf(ext) < exts.indexOf(extname(prev))) out[key] = rel;
    }
  })(dir);
  return out;
}
const images = scan(join(GAME, "assets/img"), IMAGE_EXT);
const audio = scan(join(GAME, "assets/audio"), AUDIO_EXT);

// Report which referenced images are still missing (the game falls back gracefully).
const wanted = new Set(["ui/logo", "ui/title_bg", "ui/heart_full", "ui/heart_empty"]);
for (const p of paths) {
  if (p.cover) wanted.add(`${p.id}/${p.cover}`);
  for (const n of Object.values(p.nodes)) if (n.image) wanted.add(`${p.id}/${n.image}`);
}
const missing = [...wanted].filter(k => !images[k]);
console.log(`\nImages: ${wanted.size - missing.length}/${wanted.size} present.` +
  (missing.length ? ` Missing (using fallbacks): ${missing.join(", ")}` : ""));
console.log(`Audio: ${Object.keys(audio).length ? Object.keys(audio).join(", ") : "none (game runs silent)"}`);

// ---- 3. bundle ---------------------------------------------------------------
const bundle =
  "// GENERATED by tools/build.mjs — do not edit. Source: plot/paths/*.json\n" +
  "window.HM_PATHS = " + JSON.stringify(paths) + ";\n" +
  "window.HM_ASSETS = " + JSON.stringify({ images, audio }) + ";\n" +
  "window.HM_BUILD = " + JSON.stringify(new Date().toISOString().slice(0, 10)) + ";\n";
writeFileSync(join(GAME, "js/paths.generated.js"), bundle);
console.log("\nWrote game/js/paths.generated.js");

// ---- 4. zip for itch.io -------------------------------------------------------
if (process.argv.includes("--no-zip")) process.exit(0);
mkdirSync(DIST, { recursive: true });
const zip = join(DIST, "histormania.zip");
rmSync(zip, { force: true });
const entries = ["index.html", "css", "js", "assets"];
// bsdtar (Windows 10+, macOS) writes a zip when the archive name ends in .zip.
// On Windows, call System32's tar directly: Git Bash's GNU tar can shadow it and can't write zips.
const tar = process.platform === "win32"
  ? join(process.env.SystemRoot || "C:\\Windows", "System32", "tar.exe")
  : "tar";
try {
  execFileSync(tar, ["-a", "-c", "-f", relative(GAME, zip), ...entries], { cwd: GAME, stdio: "pipe" });
  console.log(`Wrote dist/histormania.zip (${(statSync(zip).size / 1024).toFixed(0)} KB) — upload this to itch.io`);
} catch (e) {
  console.error("Could not create the zip with `tar -a` (needs bsdtar). Zip the contents of game/ manually,\n" +
    "with index.html at the root of the archive.\n" + (e.stderr?.toString() || e.message));
  process.exit(1);
}
